import { useMemo, useRef, useState } from 'react';
import type { TableColumnsType } from 'antd';
import TextInput from '@/components/inputs/TextInput';
import { useMenuPermission } from '@/hooks/use-menu-permission';
import type { CodeGroupItem, CodeGroupSearch } from '@/api/system/code-group-api';
import {
  DateTimeText,
  SysButton,
  SysExcelButton,
  SysFilterItem,
  SysFilterPanel,
  SysPage,
  SysSearchActions,
  SysSectionHeader,
  SysSplit,
  SysTable,
  SysTitleBar,
  UseBadge,
} from '@/components/common/sys-ui/SysListUi';
import { usePagedList } from '@/hooks/use-paged-list';
import { useSysDialogs } from '@/hooks/use-sys-dialogs';
import { apiErrorCode } from '@/utils/system-utils';
import { CodeDetailGrid } from './CodeDetailGrid';
import type { GridChanges, GridColumn, GridRecord } from './CodeDetailGrid';
import { CodeGroupModal } from './CodeGroupModal';
import { useBatchSaveCodes, useCodeGroups, useCodes, useDownloadCodeGroupsExcel } from './use-common-codes';
import styles from './common-code-management.module.scss';

// VPA09030101 Common Code Management: code groups (left) + editable code details (right).

// Widths fit the half-width panel without horizontal scroll; long values are cut with an ellipsis.
const CODE_COLUMNS: GridColumn[] = [
  { field: 'cd', title: 'Code', kind: 'text', required: true, isKey: true, maxLength: 100, width: '14%', sortable: true },
  { field: 'cdNm', title: 'Code Name', kind: 'text', required: true, maxLength: 100, width: '19%', sortable: true },
  { field: 'sortSeq', title: 'Order', kind: 'number', min: 0, max: 999, width: 72, sortable: true },
  { field: 'useYn', title: 'Use', kind: 'use', required: true, width: 76, sortable: true },
  // Generated by the server: never typed or built here.
  { field: 'lblCd', title: 'Label Key', kind: 'text', readOnly: true, width: '19%', sortable: true },
  { field: 'cdExpln', title: 'Remarks', kind: 'text', maxLength: 4000, sortable: true },
];

const INITIAL_FILTER: CodeGroupSearch = { groupCd: '', groupNm: '' };

const text = (value: GridRecord[string]) => (typeof value === 'string' && value !== '' ? value : undefined);

export default function CommonCodeManagement() {
  const { canWrite } = useMenuPermission();
  const { guardDiscard } = useSysDialogs();
  const list = usePagedList<CodeGroupSearch>(INITIAL_FILTER);
  const [selected, setSelected] = useState<CodeGroupItem | null>(null);
  const [modalItem, setModalItem] = useState<CodeGroupItem | null | undefined>(undefined);
  const dirty = useRef(false);

  const { data: groups = [], isFetching } = useCodeGroups(list.applied, list.sort);
  const codesQuery = useCodes(selected?.groupCd ?? null);
  const saveCodes = useBatchSaveCodes();
  const excel = useDownloadCodeGroupsExcel();

  // Latest list values (e.g. a renamed group) win over the row stored on click.
  const current = groups.find((g) => g.groupCd === selected?.groupCd) ?? selected;

  const rows = useMemo<GridRecord[]>(
    () =>
      (codesQuery.data ?? []).map((c) => ({
        cd: c.cd,
        cdNm: c.cdNm,
        sortSeq: c.sortSeq ?? null,
        useYn: c.useYn,
        lblCd: c.lblCd ?? null,
        cdExpln: c.cdExpln ?? null,
      })),
    [codesQuery.data],
  );
  const nextOrder = rows.reduce((max, r) => Math.max(max, typeof r.sortSeq === 'number' ? r.sortSeq : 0), 0) + 1;

  const selectGroup = (group: CodeGroupItem) => {
    if (group.groupCd === selected?.groupCd) return;
    guardDiscard(dirty.current, () => {
      dirty.current = false;
      setSelected(group);
    });
  };

  const handleSave = async ({ toSave, deleted }: GridChanges) => {
    if (!selected) return;
    await saveCodes.mutateAsync({
      groupCd: selected.groupCd,
      request: {
        toSave: toSave.map(({ values, isNew }) => ({
          cd: String(values.cd),
          cdNm: String(values.cdNm),
          sortSeq: typeof values.sortSeq === 'number' ? values.sortSeq : undefined,
          useYn: values.useYn === 'N' ? 'N' : 'Y',
          // Read-only: saved rows send back the key the API returned, added rows let the server generate it.
          lblCd: isNew ? undefined : text(values.lblCd),
          cdExpln: text(values.cdExpln),
          isNew,
        })),
        deleteCodes: deleted.map(String),
      },
    });
  };

  const columns: TableColumnsType<CodeGroupItem> = [
    {
      title: 'Group Code',
      dataIndex: 'groupCd',
      sorter: true,
      ellipsis: true,
      render: (value: string, row) => (
        <button
          type="button"
          title={value}
          className={styles.codeLink}
          onClick={(e) => {
            e.stopPropagation();
            setModalItem(row);
          }}
        >
          {value}
        </button>
      ),
    },
    { title: 'Group Name', dataIndex: 'groupNm', sorter: true, ellipsis: { showTitle: true } },
    { title: 'Description', dataIndex: 'groupExpln', sorter: true, ellipsis: { showTitle: true }, render: (v?: string) => v || '-' },
    { title: 'Use', dataIndex: 'useYn', sorter: true, align: 'center', width: 76, render: (v: string) => <UseBadge value={v} /> },
    {
      title: 'Registered Date',
      dataIndex: 'crtDt',
      sorter: true,
      align: 'center',
      width: 140,
      render: (v?: string) => <DateTimeText value={v} />,
    },
  ];

  return (
    <SysPage fill>
      <SysTitleBar
        title="Common Code Management"
        breadcrumb={['System Operation Management', 'Code Management', 'Common Code Management']}
      />
      <SysFilterPanel>
        <SysFilterItem label="Group Code">
          <TextInput
            value={list.draft.groupCd}
            allowClear
            onChange={(e) => list.setDraft({ groupCd: e.target.value })}
            onPressEnter={() => list.search()}
          />
        </SysFilterItem>
        <SysFilterItem label="Group Name">
          <TextInput
            value={list.draft.groupNm}
            allowClear
            onChange={(e) => list.setDraft({ groupNm: e.target.value })}
            onPressEnter={() => list.search()}
          />
        </SysFilterItem>
      </SysFilterPanel>
      <SysSearchActions onReset={list.reset} onSearch={() => list.search()} loading={isFetching} />

      <SysSplit
        ratio="1fr 1fr"
        left={
          <div className={styles.pane}>
            <SysSectionHeader
              title="Code Groups"
              total={groups.length}
              actions={<SysExcelButton loading={excel.isPending} onClick={() => excel.mutate(list.applied)} />}
              primaryActions={
                canWrite && (
                  <SysButton look="navy" onClick={() => setModalItem(null)}>
                    New
                  </SysButton>
                )
              }
            />
            <SysTable<CodeGroupItem>
              rowKey="groupCd"
              fill
              className={`${styles.paneBody} ${styles.stickyHead}`}
              columns={columns}
              dataSource={groups}
              // Fixed layout fits the panel; the whole list scrolls inside it (no pager).
              tableLayout="fixed"
              loading={isFetching}
              onRowClick={selectGroup}
              selectedRowKey={selected?.groupCd}
              sort={list.sort}
              onSortChange={list.setSort}
            />
          </div>
        }
        right={
          <div className={styles.pane}>
            <CodeDetailGrid
              key={`${selected?.groupCd ?? ''}-${codesQuery.dataUpdatedAt}`}
              title={current ? `[${current.groupNm}] Code Details` : 'Code Details'}
              disabled={!selected}
              emptyText="Select a code group."
              canWrite={canWrite}
              loading={codesQuery.isFetching}
              columns={CODE_COLUMNS}
              rows={rows}
              newRowDefaults={{ cd: '', cdNm: '', sortSeq: nextOrder, useYn: 'Y', lblCd: '', cdExpln: '' }}
              saving={saveCodes.isPending}
              onSave={handleSave}
              isDuplicateError={(e) => apiErrorCode(e) === 'COD004'}
              onDirtyChange={(value) => (dirty.current = value)}
            />
          </div>
        }
      />

      {modalItem !== undefined && (
        <CodeGroupModal
          key={modalItem?.groupCd ?? 'new'}
          item={modalItem}
          canWrite={canWrite}
          onClose={() => setModalItem(undefined)}
        />
      )}
    </SysPage>
  );
}
