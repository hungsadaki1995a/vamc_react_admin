import { useState } from 'react';
import { DatePicker, Input, Select, Spin } from 'antd';
import dayjs from 'dayjs';
import type { Dayjs } from 'dayjs';
import { useNotify } from '@/hooks/use-notify';
import type { TermsPolicyDetail, TermsType } from '@/api/system/terms-api';
import { SysField, SysFieldGrid, SysFormModal } from '@/features/system/_shared/sys-form-ui';
import { SysButton } from '@/features/system/_shared/sys-list-ui';
import { API_DATE_ISO, SYS_DATE_FORMAT } from '@/features/system/_shared/sys-constants';
import { SYS_DIALOG_LABELS, SYS_MESSAGES } from '@/features/system/_shared/sys-messages';
import { useFieldErrors } from '@/features/system/_shared/use-field-errors';
import { useSysDialogs } from '@/features/system/_shared/use-sys-dialogs';
import { apiErrorCode, errorMessage } from '@/features/system/_shared/system-utils';
import { TERMS_MESSAGES, TERMS_TYPE_OPTIONS } from './terms-constants';
import { useCreateTermsPolicy, useDeleteTermsPolicy, useTermsPolicy, useUpdateTermsPolicy } from './use-terms-policies';
import styles from './terms-management.module.scss';

// VPA090107P01 Terms Register / Edit (Scheduled) / Detail (In Effect, Previous Version).
// Version is generated by the server and status follows the effective date: no publish step.

type Field = 'type' | 'effectiveDate' | 'content' | 'contentEn';

const isFromTomorrow = (date: Dayjs) => date.startOf('day').isAfter(dayjs().startOf('day'));

interface TermsFormModalProps {
  /** null = register. */
  detail: TermsPolicyDetail | null;
  canWrite: boolean;
  onClose: () => void;
}

function TermsFormModal({ detail, canWrite, onClose }: TermsFormModalProps) {
  const isCreate = detail === null;
  const readOnly = !isCreate && detail.status !== 'SCHEDULED';
  const { toast } = useNotify();
  const { confirm } = useSysDialogs();
  const { errors, setError, clearError, checkRequired, applyApiError } = useFieldErrors<Field>();
  const [values, setValues] = useState({
    type: (detail?.type ?? 'TRMS') as TermsType,
    effectiveDate: (detail?.effectiveDate ? dayjs(detail.effectiveDate) : null) as Dayjs | null,
    content: detail?.content ?? '',
    contentEn: detail?.contentEn ?? '',
  });
  const createTerms = useCreateTermsPolicy();
  const updateTerms = useUpdateTermsPolicy();
  const deleteTerms = useDeleteTermsPolicy();

  const change = <K extends Field>(key: K, value: (typeof values)[K]) => {
    setValues((prev) => ({ ...prev, [key]: value }));
    clearError(key);
  };

  const handleSubmit = async () => {
    if (!checkRequired(values, ['type', 'effectiveDate', 'content'])) return;
    const effectiveDate = values.effectiveDate as Dayjs;
    if (!isFromTomorrow(effectiveDate)) {
      setError('effectiveDate', TERMS_MESSAGES.fromTomorrow);
      return;
    }
    const request = {
      effectiveDate: effectiveDate.format(API_DATE_ISO),
      content: values.content,
      contentEn: values.contentEn.trim() ? values.contentEn : undefined,
    };
    try {
      if (isCreate) {
        await createTerms.mutateAsync({ type: values.type, ...request });
        toast.success(SYS_MESSAGES.registered);
      } else {
        await updateTerms.mutateAsync({ termsId: detail.termsId, request });
        toast.success(SYS_MESSAGES.updated);
      }
      onClose();
    } catch (e) {
      const handled = applyApiError(e, {
        TRM003: ['effectiveDate', TERMS_MESSAGES.duplicateDate],
        TRM007: ['effectiveDate', TERMS_MESSAGES.fromTomorrow],
      });
      if (!handled) toast.error(apiErrorCode(e) === 'TRM004' ? TERMS_MESSAGES.locked : errorMessage(e));
    }
  };

  const handleDelete = () => {
    if (!detail) return;
    confirm({
      content: TERMS_MESSAGES.confirmDelete,
      okText: SYS_DIALOG_LABELS.delete,
      danger: true,
      onOk: async () => {
        try {
          await deleteTerms.mutateAsync(detail.termsId);
          toast.success(SYS_MESSAGES.deleted);
          onClose();
        } catch (e) {
          toast.error(apiErrorCode(e) === 'TRM008' ? TERMS_MESSAGES.locked : errorMessage(e));
        }
      },
    });
  };

  const editable = canWrite && !readOnly;
  const title = isCreate ? 'Register Terms' : readOnly ? 'Terms Detail' : 'Edit Terms';

  return (
    <SysFormModal
      open
      title={title}
      submitText={isCreate ? 'Register' : 'Edit'}
      onSubmit={editable ? () => void handleSubmit() : undefined}
      submitting={createTerms.isPending || updateTerms.isPending}
      onCancel={onClose}
      extraActions={
        !isCreate &&
        editable && (
          <SysButton className={styles.deleteAction} look="primary" danger loading={deleteTerms.isPending} onClick={handleDelete}>
            Delete
          </SysButton>
        )
      }
    >
      <SysFieldGrid columns={2}>
        <SysField label="Terms Type" required error={errors.type}>
          <Select
            className={styles.fullWidth}
            options={TERMS_TYPE_OPTIONS}
            value={values.type}
            disabled={!isCreate}
            onChange={(v: TermsType) => change('type', v)}
          />
        </SysField>
        <SysField
          label="Effective Date"
          required
          error={errors.effectiveDate}
          hint={editable ? 'From tomorrow; one version per date and type.' : undefined}
        >
          <DatePicker
            className={styles.fullWidth}
            format={SYS_DATE_FORMAT}
            value={values.effectiveDate}
            disabled={!editable}
            disabledDate={(d) => !isFromTomorrow(d)}
            onChange={(d) => change('effectiveDate', d)}
          />
        </SysField>
        <SysField label="Content (VN)" required span="full" error={errors.content}>
          <Input.TextArea
            rows={10}
            value={values.content}
            readOnly={!editable}
            onChange={(e) => change('content', e.target.value)}
          />
        </SysField>
        <SysField
          label="Content (EN)"
          span="full"
          error={errors.contentEn}
          hint={editable ? 'If empty, the VN original is shown on the English user screen.' : undefined}
        >
          <Input.TextArea
            rows={10}
            value={values.contentEn}
            readOnly={!editable}
            onChange={(e) => change('contentEn', e.target.value)}
          />
        </SysField>
      </SysFieldGrid>
    </SysFormModal>
  );
}

interface TermsModalProps {
  /** null = register; otherwise the row to open. */
  termsId: string | null;
  canWrite: boolean;
  onClose: () => void;
}

/** Loads the detail (content) before opening the edit / detail form. */
export function TermsModal({ termsId, canWrite, onClose }: TermsModalProps) {
  const { data, isError, error } = useTermsPolicy(termsId);
  if (termsId === null) return <TermsFormModal detail={null} canWrite={canWrite} onClose={onClose} />;
  if (data) return <TermsFormModal key={data.termsId} detail={data} canWrite={canWrite} onClose={onClose} />;
  return (
    <SysFormModal open title="Terms Detail" onCancel={onClose}>
      <div className={styles.loading}>{isError ? errorMessage(error) : <Spin />}</div>
    </SysFormModal>
  );
}
