import { apiDelete, apiDownload, apiGet, apiPatch, apiPost, apiPut } from '@/api/common/api-utils';
import type { PageQuery, PageResponse } from '@/api/common/api-utils';

// Fee Management API — FeeController (`/api/v1/platform/fees`), guard menu A09010300, table SRVC_FEE_MNG.
// Screens VPA09010301 (list) / VPA090103P01 (register/edit) / VPA090103P02 (fee schedule).

/** COM_CD FEE_ARTCL_SE_CD accepted on save. */
export type FeeCategory = 'ANFE' | 'PMDT' | 'DMDT' | 'CNSLT';
/** Old brokerage type; still listed but rejected on save (FEE004). */
export const LEGACY_FEE_CATEGORY = 'MDT';
/** COM_CD FEE_LEVY_MTH_CD — FXAMT = fixed amount, TRF = rate (%). */
export type FeeMethod = 'FXAMT' | 'TRF';
export type FeeCurrency = 'VND' | 'USD';
export type YesNo = 'Y' | 'N';

export interface Fee {
  /** FEE-MBR- / FEE-PBR- / FEE-SBR- / FEE-CNS- + 4 digits. */
  feeId: string;
  batchCd?: string;
  useYn: YesNo;
  /** FeeCategory, or the legacy `MDT`. */
  category: string;
  categoryNm?: string;
  order: number;
  name: string;
  description?: string;
  method: FeeMethod;
  methodNm?: string;
  currency: FeeCurrency;
  /** Fixed amount (FXAMT). */
  fee?: number;
  /** Percent (TRF). */
  rate?: number;
  /** Minimum applicable amount (TRF). */
  minAmount?: number;
  minAmountCurrency?: string;
  /** DDMMYYYY of the batch. */
  effectiveFrom?: string;
  note?: string;
  /** Always true since v0.8. */
  editable: boolean;
  crtDt?: string;
  crtBy?: string;
  crtByNm?: string;
  mdfcnDt?: string;
  mdfcnBy?: string;
}

export interface FeeSearch {
  useYn?: YesNo | '';
  category?: FeeCategory | '';
  /** dd/MM/yyyy (registration date). */
  fromDate?: string;
  /** dd/MM/yyyy, inclusive. */
  toDate?: string;
  /** Partial match on item name / content. */
  keyword?: string;
}

export interface FeeRequest {
  category: FeeCategory;
  /** 1–99 */
  order: number;
  /** ≤ 300 */
  name: string;
  /** ≤ 1000 */
  description?: string;
  method: FeeMethod;
  currency: FeeCurrency;
  /** Required when method = FXAMT. */
  fee?: number;
  /** Required when method = TRF; 0 < rate ≤ 100. */
  rate?: number;
  minAmount?: number;
  /** Create defaults to Y; update keeps the current value when omitted. */
  useYn: YesNo;
}

/**
 * Error codes: FEE002 not found, FEE004 invalid type / method, FEE005 amount or rate missing,
 * FEE001 in use (delete only), FEE003 referenced by an application fee group (delete only).
 */
export const FEE_ERRORS = {
  inUse: 'FEE001',
  notFound: 'FEE002',
  referenced: 'FEE003',
  invalid: 'FEE004',
  amountRequired: 'FEE005',
} as const;

const BASE = '/api/v1/platform/fees';

export const getFees = (search: FeeSearch, query: PageQuery) =>
  apiGet<PageResponse<Fee>>(BASE, { ...search, ...query });

export const getFee = (feeId: string) => apiGet<Fee>(`${BASE}/${encodeURIComponent(feeId)}`);

/** The fee code is generated by the server. */
export const createFee = (request: FeeRequest) => apiPost<Fee>(BASE, request);

/** Editable while in use; Use is saved in the same call. */
export const updateFee = (feeId: string, request: FeeRequest) =>
  apiPut<Fee>(`${BASE}/${encodeURIComponent(feeId)}`, request);

/** Use switch — only used for legacy `MDT` rows, which PUT rejects. */
export const changeFeeUse = (feeIds: string[], useYn: YesNo) => apiPatch<number>(`${BASE}/use`, { feeIds, useYn });

/** Only for legacy `MDT` rows: items not in use (FEE001) and not referenced (FEE003). */
export const deleteFees = (feeIds: string[]) => apiDelete<number>(BASE, { feeIds });

export const downloadFeeExcel = (search: FeeSearch) => apiDownload(`${BASE}/excel`, 'fees.xlsx', search);

