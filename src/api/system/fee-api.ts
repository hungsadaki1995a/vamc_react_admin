import { apiDelete, apiDownload, apiGet, apiPatch, apiPost, apiPut } from '@/api/common/api-utils';
import type { PageResponse } from '@/api/common/api-utils';

// Fee Management API — FeeController (`/api/v1/platform/fees`), guard menu A06010300.
// Screens VPA004101 (list) / VPA0041P01 (popup). Table SRVC_FEE_MNG.

/** COM_CD FEE_ARTCL_SE_CD */
export type FeeCategory = 'ANFE' | 'CNSLT' | 'MDT';
/** COM_CD FEE_LEVY_MTH_CD — FXAMT = fixed amount, TRF = rate (%) */
export type FeeMethod = 'FXAMT' | 'TRF';
export type FeeCurrency = 'VND' | 'USD';

export interface Fee {
  feeId: string;
  batchCd?: string;
  useYn: 'Y' | 'N';
  category: FeeCategory;
  categoryNm?: string;
  order: number;
  name: string;
  description?: string;
  method: FeeMethod;
  methodNm?: string;
  currency: FeeCurrency;
  /** Fixed amount (FXAMT). */
  fee?: number;
  /** Percent (TRF). */
  rate?: number;
  /** Minimum applicable amount (TRF). */
  minAmount?: number;
  minAmountCurrency?: string;
  note?: string;
  /** true only while useYn = N. */
  editable: boolean;
  crtDt?: string;
  crtBy?: string;
  crtByNm?: string;
  mdfcnDt?: string;
  mdfcnBy?: string;
}

export interface FeeSearch {
  useYn?: 'Y' | 'N';
  category?: FeeCategory;
  /** dd/MM/yyyy */
  fromDate?: string;
  /** dd/MM/yyyy, inclusive */
  toDate?: string;
  /** LIKE on fee id / item name / description */
  keyword?: string;
}

export interface FeeRequest {
  category: FeeCategory;
  /** 1–99 */
  order: number;
  name: string;
  description?: string;
  method: FeeMethod;
  currency: FeeCurrency;
  /** Required when method = FXAMT. */
  fee?: number;
  /** Required when method = TRF; 0 < rate <= 100. */
  rate?: number;
  minAmount?: number;
  note?: string;
}

const BASE = '/api/v1/platform/fees';

export const getFees = (search: FeeSearch, page: number, size: number) =>
  apiGet<PageResponse<Fee>>(BASE, { ...search, page, size });

export const getFee = (feeId: string) => apiGet<Fee>(`${BASE}/${feeId}`);

/** New items are always created with useYn = N; the fee id is generated by the server. */
export const createFee = (request: FeeRequest) => apiPost<Fee>(BASE, request);

/** Only allowed while the item is not in use (409 FEE001 otherwise). */
export const updateFee = (feeId: string, request: FeeRequest) =>
  apiPut<Fee>(`${BASE}/${feeId}`, request);

export const changeFeeUse = (feeIds: string[], useYn: 'Y' | 'N') =>
  apiPatch<number>(`${BASE}/use`, { feeIds, useYn });

/** Rejected when any item is in use (FEE001) or referenced by a fee group (FEE003). */
export const deleteFees = (feeIds: string[]) => apiDelete<number>(BASE, { feeIds });

export const downloadFeeExcel = (search: FeeSearch) =>
  apiDownload(`${BASE}/excel`, 'fees.xlsx', search);
